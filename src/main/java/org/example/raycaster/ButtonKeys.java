package org.example.raycaster;

public class ButtonKeys {
    public boolean FORWARD, BACKWARD, LEFT, RIGHT, SHIFT, LOOK_UP, LOOK_DOWN;

    //1 = on
    //0 = off
    public ButtonKeys() {
        this.FORWARD = false;
        this.BACKWARD = false;
        this.LEFT = false;
        this.RIGHT = false;
        this.SHIFT = false;
        this.LOOK_UP = false;
        this.LOOK_DOWN = false;
    }
}
